function applyRoman(string $s, array $phrases, array $tokens): string {
    // 1) phrases (longest first), case-insensitive, preserve a trailing/leading space structure
    $pl = $phrases;
    uksort($pl, fn($a,$b) => strlen($b) <=> strlen($a));
    foreach ($pl as $en => $ro) {
        $s = preg_replace('/' . preg_quote($en, '/') . '/iu', $ro, $s);
    }
    // 2) tokens as whole words, case-insensitive
    foreach ($tokens as $en => $ro) {
        $pat = '/\b' . preg_quote($en, '/') . '\b/iu';
        $s = preg_replace($pat, $ro, $s);
    }
    // collapse double spaces, fix space before punctuation
    $s = preg_replace('/ {2,}/', ' ', $s);
    $s = preg_replace('/ +([:,.;)\]])/', '$1', $s);
    $s = preg_replace('/([(\[]) +/', '$1', $s);
    return trim($s);
}

